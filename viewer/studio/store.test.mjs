import assert from "node:assert/strict";
import { store } from "./store.js";
const memory = new Map();
globalThis.localStorage = { getItem: (k) => memory.get(k) ?? null, setItem: (k, v) => memory.set(k, v), removeItem: (k) => memory.delete(k) };
assert.equal(store.state.showFaceOutlines, false);
let outlineChange = null;
const offOutline = store.on("change:showFaceOutlines", (value) => { outlineChange = value; });
store.set({ showFaceOutlines: true });
assert.equal(outlineChange, true);
offOutline();
store.set({ model: "first" });
store.loadDraft();
assert.equal(store.canUndo(), false);
const id = store.addItem({ type: "pin", point: [0, 0, 0], note: "保存するメモ" });
assert.equal(store.canUndo(), true);
store.removeItem(id);
assert.equal(store.state.draft.items.length, 0);
store.undo();
assert.equal(store.state.draft.items[0].note, "保存するメモ");
assert.equal(store.canRedo(), true);
store.setMessage("モデル固有のメモ");
store.set({ model: "second" });
store.loadDraft();
assert.equal(store.state.draft.items.length, 0);
store.set({ model: "first" });
store.loadDraft();
assert.equal(store.state.draft.message, "モデル固有のメモ");
assert.equal(store.canUndo(), false);
memory.set("studio.draft.first", JSON.stringify({ message: null, items: [null, 5, { id: "a", type: "pin" }] }));
store.loadDraft();
assert.equal(store.state.draft.message, "");
assert.equal(store.state.draft.items.length, 1);
store.set({ layout: { kind: "plate", id: "plate-a" } });
store.loadDraft();
assert.equal(store.state.draft.items.length, 0);
store.setMessage("プレートのメモ");
store.set({ layout: { kind: "assembled" } });
store.loadDraft();
assert.equal(store.state.draft.message, "");
store.set({ layout: { kind: "plate", id: "plate-a" } });
store.set({ sectionTransform: "rotate" });
store.loadDraft();
assert.equal(store.state.draft.message, "プレートのメモ");
assert.equal(store.state.sectionTransform, "off");
assert.equal(store.canUndo(), false);
store.set({ sectionTransform: "translate" });
store.clearDraft();
assert.equal(store.state.sectionTransform, "off");
console.log("store: 18 assertions passed");

// 部品の見え方: モデルごとに保存し、読み直しても残る。下書きの undo には入らない
store.set({ model: "cube" });
store.loadPartModes();
assert.deepEqual(store.state.partModes, {});
let modeChange = null;
const offModes = store.on("change:partModes", (v) => { modeChange = v; });
store.setPartMode("housing.stl", "ghost");
assert.deepEqual(modeChange, { "housing.stl": "ghost" });
assert.equal(memory.get("studio.partModes.cube"), JSON.stringify({ "housing.stl": "ghost" }));
store.setPartMode("lid.stl", "hidden");
store.set({ model: "other" });
store.loadPartModes();
assert.deepEqual(store.state.partModes, {});
store.set({ model: "cube" });
store.loadPartModes();
assert.deepEqual(store.state.partModes, { "housing.stl": "ghost", "lid.stl": "hidden" });
store.setPartMode("lid.stl", "normal");
assert.deepEqual(store.state.partModes, { "housing.stl": "ghost" });
store.resetPartModes();
assert.deepEqual(store.state.partModes, {});
assert.equal(memory.has("studio.partModes.cube"), false);
memory.set("studio.partModes.cube", "{壊れた");
store.loadPartModes();
assert.deepEqual(store.state.partModes, {});
offModes();
console.log("store part modes: 9 assertions passed");

// ユーザーの呼び名: モデルごとに保存し、読み直しても残る。台帳の名前と同じなら消える
const part = { id: "cam_0", label: "カム 0", systemLabel: "カム 0" };
store.set({ model: "cube" });
store.loadPartNames();
assert.deepEqual(store.state.partNames, {});
store.setPartName(part, "最初のカム");
assert.deepEqual(store.state.partNames, { cam_0: { label: "最初のカム" } });
assert.equal(memory.get("studio.partNames.cube"), JSON.stringify({ cam_0: { label: "最初のカム" } }));
store.set({ model: "other" });
store.loadPartNames();
assert.deepEqual(store.state.partNames, {});
store.set({ model: "cube" });
store.loadPartNames();
assert.deepEqual(store.state.partNames, { cam_0: { label: "最初のカム" } });
store.setPartName(part, "カム 0");
assert.deepEqual(store.state.partNames, {});
assert.equal(memory.has("studio.partNames.cube"), false);
store.setPartName(part, "x");
store.resetPartNames();
assert.deepEqual(store.state.partNames, {});
memory.set("studio.partNames.cube", "{壊れた");
store.loadPartNames();
assert.deepEqual(store.state.partNames, {});
// 指している部品（表示だけ）: 同じ内容なら出来事を出さない。下書きの undo には入らない
let hoverEvents = 0;
const offHover = store.on("change:partHover", () => { hoverEvents += 1; });
store.hoverParts(["a"]);
store.hoverParts(["a"]);
assert.equal(hoverEvents, 1);
store.hoverParts("b");
assert.deepEqual(store.state.partHover, ["b"]);
store.hoverParts([]);
store.hoverParts(null);
assert.equal(hoverEvents, 3);
offHover();
console.log("store part names: 12 assertions passed");
