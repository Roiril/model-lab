"""28mm パイプ用 180 度ヘアピン（U ターン）の寸法定義。手すり用。

すべて mm。ローカル座標:
    円弧の中心が原点、U は XY 平面に寝ている
    Z=0 がパイプの芯の高さ。両端の差し込み口は +X 方向を向く

左右レール（Y=±80）の端どうしをつなぐ。芯線半径 R = レール間隔の半分。

断面（手すりとして握る形）:
    上半分は半径 HUB_R の半円。手が当たるのは全部この丸み
    横は垂直、下は平ら。ベッドに着く面を確保するためで、握りには関わらない
    下の角は 45 度の面取り。ここまでなら無支持で出る

印刷の前提: この向きのまま寝かせて刷る。
    - 断面が上へ行くほど細るだけなので、外側にオーバーハングが無い
    - 中を通る穴は横向きなので、天井を 45 度の屋根にして自立させる
"""

MM = 0.001

# --- パイプ ---
PIPE_OD = 28.0
CLEAR = 0.30
BORE_D = PIPE_OD + 2 * CLEAR       # 28.6

# --- 断面 ---
WALL = 4.0
HUB_R = BORE_D / 2 + WALL          # 18.3 握り部の半径（外径 36.6）
TIP_WALL = 0.4                     # 差し込み口の先端に残す肉厚
TIP_R = BORE_D / 2 + TIP_WALL      # 14.7 口元の半径 → パイプ面からの段差 0.7mm
MOUTH_TAPER = 16.0                 # 口元で HUB_R → TIP_R に落とす長さ

BOT_WALL = 3.0                     # 穴の下に残す肉厚（人が体重をかける前提で薄くしすぎない）
Z_BASE = BORE_D / 2 + BOT_WALL     # 16.3 芯から底面までの深さ
BOT_CHAMFER = 4.0                  # 底の角の 45 度面取り

# --- 芯線 ---
R = 80.0                           # 円弧の芯線半径（＝レール Y 間隔 160 の半分）
STRAIGHT = 55.0                    # 両端の直線部（＝パイプの差し込み長）

# --- ティアドロップ（横向きの穴を自立させる屋根）---
TD_TOP = HUB_R - WALL              # 14.3 芯からの高さ

# --- メッシュ品質 ---
ARC_SEG = 120                      # 180 度を割る数
STR_SEG = 28                       # 直線部の分割数
PROF_SEG = 48                      # 断面の上半円の分割数

# --- 参照パイプ（フィット確認用。印刷対象ではない）---
REF_LEN = 200.0
