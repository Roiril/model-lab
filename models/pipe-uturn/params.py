"""28mm パイプ用 180 度ヘアピン（U ターン）の寸法定義。

すべて mm。ローカル座標:
    円弧の中心が原点、U は XY 平面に寝ている（Z=0 が断面の中心）
    両端の差し込み口は +X 方向を向く

左右レール（Y=±80）の端どうしをつなぐ。芯線半径 R = レールの Y 間隔の半分。

印刷の前提: Z を上にして寝かせたまま刷る。
    - 外形は Z 方向に一様な押し出し（プリズム）。底面が丸ごとベッドに着く
    - 中を通る穴は横向きなので、断面をティアドロップにして全長を自立させる
    - 底の角だけ後から切って平らに戻す
"""

MM = 0.001

# --- パイプ ---
PIPE_OD = 28.0
CLEAR = 0.30
BORE_D = PIPE_OD + 2 * CLEAR       # 28.6

# --- 断面 ---
WALL = 4.0
HUB_D = BORE_D + 2 * WALL          # 36.6 外形の一辺（幅・高さとも）
BODY_H = HUB_D                     # 36.6 Z 方向の高さ
BAND_W = HUB_D                     # 36.6 半径方向の幅

# --- 芯線 ---
R = 80.0                           # 円弧の芯線半径（＝レール Y 間隔 160 の半分）
STRAIGHT = 55.0                    # 両端の直線部（＝パイプの差し込み長）

# --- ティアドロップ（横向きの穴を自立させる屋根）---
# 屋根の頂点は軸から BORE_D/2*sqrt(2)=20.22 上。壁を WALL 残すところで切る。
TD_TOP = BODY_H / 2 - WALL         # 14.3 軸からの高さ

# --- 仕上げ ---
FILLET_R = 4.0                     # 縦エッジの R
FILLET_ANGLE = 25.0
BASE_ROUND = 1.5                   # 底の角丸（後で平らに切る分）

# --- メッシュ品質 ---
ARC_SEG = 96                       # 180 度を割る数
PROF_SEG = 64                      # 断面の分割数
FILLET_SEG = 4

# --- 参照パイプ（フィット確認用。印刷対象ではない）---
REF_LEN = 200.0
