# CATEGORY: フィギュア
# meccha-chameleon — 『めっちゃカメレオン』の隠れ側プレイヤーアバター。
#
# ゲーム内の操作キャラは「真っ白でディテールの無いツルッとした人型」。
# プレイヤーが体に絵を描いて背景に溶け込み、複数のポーズ（エモート）を取る。
# ここではその素体を、丸い関節でつないだマネキン状の人型として再現し、
# 代表的なポーズを別STLとして出力する。
#
# 単位はすべてメートル（1mm = 0.001）。コメント `# ラベル` がスライダー名。

# --- 全体スケール ---
SCALE = 1.0        # 全体倍率（0.7 で約7cm に縮む）

# --- 体節の太さ（物理半径・メートル） ---
# 関節を見せず一体的に滑らかにつながる人型（やや柔らかめの自然プロポーション）。
# 関節玉は置かず、太い体節どうしをメタボールで融合させて継ぎ目を消す。
# 実物プリント写真に合わせた「大きい頭・かわいいチビ体型」（約3.4頭身）
# サブエージェント比較レビュー反映: 胴を短く均一に・肩>腰のテーパー・脚を長く・首を詰める
R_TORSO = 0.0125   # 胴の太さ（半径）
R_NECK  = 0.0066   # 首の太さ（短く滑らかに肩へ）
R_HEAD  = 0.0140   # 頭の大きさ（半径）← 大きい丸い頭
R_ARM   = 0.0056   # 腕の太さ
R_HAND  = 0.0056   # 手（前腕先の丸い終端）
R_LEG   = 0.0078   # 脚の太さ
R_FOOT  = 0.0080   # 足（大きめにして接地を安定）

# --- 体節の長さ（メートル） ---
L_SPINE  = 0.018   # 骨盤→胸（短く＝寸胴のピーナツ化を防ぐ）
L_NECK   = 0.003   # 胸→首（ごく短い＝頭が肩に近い）
L_HEADUP = 0.011   # 首→頭中心
SH_W     = 0.0130  # 肩の横ひろがり（中心から）← 腰より広く
SH_UP    = 0.002   # 肩の高さ（胸から）
L_UARM   = 0.0175  # 上腕
L_LARM   = 0.017   # 前腕（手が太もも上部に届く長さ）
HIP_W    = 0.0075  # 股関節の横ひろがり（腰を絞る）
HIP_DN   = 0.0000  # 股関節の下がり（垂れ尻を防ぐ）
L_ULEG   = 0.022   # 太もも（長く）
L_LLEG   = 0.020   # すね（長く）

# --- 足（前方に伸びる楕円体） ---
FOOT_FWD = 0.0050  # 足のつま先側の伸び
FOOT_FLAT = 0.65   # 足の上下つぶし率（1=球, 小さいほど平たい）

# --- 台座（直立ポーズの転倒防止） ---
BASE_ON   = 1      # 台座を付ける（1=付ける / 0=無し）
BASE_T    = 0.003  # 台座の厚み
BASE_MARGIN = 0.004  # 足元から外側へのはみ出し
BASE_OVERLAP = 0.0015  # 足に食い込ませる量（一体化のため）

# --- メタボール（造形の滑らかさ） ---
# 注: Blender の metaball.resolution は 0.005m が下限クランプ。100mm の素体には粗い。
# そこで BUILD_SCALE 倍に拡大して多角形化し、後で縮小して実寸へ戻す。
MB_RES      = 0.005  # メタボール多角形化解像度（下限クランプ値）
BUILD_SCALE = 12     # 多角形化時の拡大率（実効解像度 ≈ 5mm/12 ≈ 0.42mm）
REMESH_VOXEL = 0.0006  # ボクセル・リメッシュの一辺（0.6mm）。素体を多様体化しゴミを除去
MB_STIFF  = 2.0     # 各要素の硬さ
MB_THRESH = 0.35    # 表面しきい値（小さいほど場が締まり水かき・脚の癒着が減る）

