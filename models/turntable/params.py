# プリント・イン・プレース回転台 — 寸法・定数（単位: m）
#
# 構造（同軸・z上向き）:
#   固定部 = ベース円板 + 中心軸 + 天面の傘（キノコ）
#   ローター = リング円板（軸まわりに自由回転、ベースと傘に挟まれて抜けない）
# すべて隙間を空けて一体プリント（組立不要）。

import math  # noqa: F401  （model 側で使う場合あり）

# --- クリアランス（プリント・イン・プレースの肝）---
GAP_Z = 0.0003    # 0.3mm 縦クリアランス（ローター上下。ブリッジで融着しない最小）
GAP_R = 0.0004    # 0.4mm 半径クリアランス（ローター内壁 ↔ 軸）

# --- 固定部: ベース円板 ---
BASE_R = 0.020    # 20mm 半径（接地を広く取り安定）
BASE_T = 0.003    # 3mm 厚

# --- 固定部: 中心軸 ---
SHAFT_R = 0.004   # 4mm 半径

# --- ローター（リング円板）---
ROTOR_R  = 0.016  # 16mm 外径半径
ROTOR_T  = 0.006  # 6mm 厚
ROTOR_IR = SHAFT_R + GAP_R   # 内径半径 = 軸 + クリアランス

# --- 固定部: 傘（ローター抜け止め）---
CAP_OVERLAP = 0.003   # ローター内縁を覆うかぶり量
CAP_R = ROTOR_IR + CAP_OVERLAP   # 傘半径
CAP_T = 0.002         # 2mm 厚

# --- 派生 z 座標 ---
ROTOR_Z0 = BASE_T + GAP_Z              # ローター下面
ROTOR_Z1 = ROTOR_Z0 + ROTOR_T          # ローター上面
CAP_Z0   = ROTOR_Z1 + GAP_Z            # 傘下面
SHAFT_TOP = CAP_Z0                      # 軸上端（傘下面まで）
TOTAL_H  = CAP_Z0 + CAP_T              # 全高

# --- 回転確認用マーカー突起 ---
MARK_W = 0.0025   # 2.5mm 角
MARK_H = 0.0015   # 1.5mm 高
