# Pixel 7a 入隅マウント（部屋の縦の角に両面テープで貼る）— 寸法・定数（単位: m）
#
# 正面版 models/pixel7a-wallmount はスマホを壁の正面へ向ける。こちらは 2 枚の壁が
# 直角に交わる角へ貼り、スマホをその二等分線＝どちらの壁からも 45° の方向へ向ける。
# 壁 1 枚に貼って首を 45° 振る作りにすると、振った分だけ壁との間に三角の空隙が生まれ、
# そこを骨組みで埋めることになる。角に貼れば部屋側から見て死んでいる空間がそのまま
# 空隙になるので、埋める必要が無い。
import math

# --- Pixel 7a 実寸（Google 公式スペック） ---
PHONE_L    = 0.1520   # 152.0mm 長辺（横向きに入れるので幅方向）
PHONE_W    = 0.0729   # 72.9mm 短辺（スロットを上る方向）
PHONE_T    = 0.0090   # 9.0mm 厚み（カメラバー部を除く）
PHONE_BUMP = 0.0011   # カメラバーの出っ張り 1.1mm（窓から外へ出す）

# --- クリアランス（片側）— 据置版で実機が入った値をそのまま使う ---
CLR_L = 0.0007   # 長辺方向 0.7mm
CLR_W = 0.0007   # 短辺方向 0.7mm
CLR_T = 0.0008   # 厚み方向 0.8mm

# --- スロット内寸 ---
SLOT_L = PHONE_L + 2 * CLR_L   # 153.4mm 幅方向
SLOT_W = PHONE_W + 2 * CLR_W   #  74.3mm スロットを上る方向
SLOT_T = PHONE_T + CLR_T       #   9.8mm 厚み方向

# --- 肉厚 ---
FRONT_SKIN = 0.0025   # 2.5mm 外皮。スマホ背面を下から受ける面で、カメラ窓が開く
BACK_PLATE = 0.0030   # 3.0mm 裏板。スマホ画面側で上を向く
SIDE_WALL  = 0.0035   # 3.5mm 側壁
STOPPER    = 0.0035   # 3.5mm スロット下端の受け（スマホはここで止まる）

SHELL_TOTAL = FRONT_SKIN + SLOT_T + BACK_PLATE   # 15.3mm ポケットの総厚

# --- 姿勢 ---
# スマホ面を水平から TILT_DEG 倒す。背面の法線＝カメラの視線は (90 - TILT) 度だけ下を向く。
# 横方向は 2 枚の壁の二等分線を向くので、どちらの壁から見ても 45°。
TILT_DEG       = 50.0
CAM_DEPRESSION = 90.0 - TILT_DEG   # 40.0° カメラの俯角

SLOPE_LEN  = STOPPER + SLOT_W + 0.0008   # 78.6mm ポケットの長さ
SLOT_ENTRY = 0.0600   # 差し込み口を抜くためのカッター延長

MOUNT_W = SLOT_L + 2 * SIDE_WALL   # 160.4mm ポケットの幅

# --- 角に対する位置 ---
# 角から二等分線に沿って測った距離を u とする。壁は u = ±v（v は幅方向）の 2 面。
# ポケットの幅の半分だけ角から離さないと、後ろ下の角が壁へめり込む。
CORNER_SET = 0.0070   # 7.0mm 余分に前へ出す（最寄り点で壁から垂直 5.0mm 空く）
U_BACK     = MOUNT_W / 2 + CORNER_SET   # 87.2mm ポケット後端の u

# --- ウィング（ポケット側面と壁を渡す中空の三角柱。外面が貼付面） ---
# 角の側ではなくポケットの外側へ張り出す。角の側へ回すと、ポケットが前へ倒れている分だけ
# 上へ行くほど壁との距離が開き、そこを埋める箱が要る。外側なら側壁へ直付けできる。
WING_T     = 0.0030   # 3.0mm 殻の厚み
WING_BITE  = 0.0020   # 2.0mm ポケット側壁へ食い込ませる量（重なりで一体化させる）
WING_REAR  = 0.0040   # 4.0mm 壁と側壁が交わる稜は刃物のように薄くなるので落とす
PAD_OVER   = 0.0030   # 3.0mm ポケット前面より前へ出す量
# 壁の上を前へ伸ばすほど貼付面は広がるが、幅方向にも同じだけ広がる（壁の上では u=v）。
# 全幅 200mm でベッドに載る側に振った。
WING_VMAX  = 0.1000   # 100.0mm 幅方向の打ち切り（全幅 200mm）
# ポケットの上へ伸ばす高さ。前へ倒れようとする力は、貼付面の上端を壁から引き剥がす
# 向きに効く。この腕（貼付面の高さ）を伸ばすと、剥がす力は高さの 2 乗で減る。
# 60mm → 110mm で 1/3.4。ウィングは閉じた筒なので、伸ばした分がそのまま働く。
WING_H     = 0.1100   # 110.0mm ウィングと貼付面の高さ（ポケットの上端は 70mm）
WING_TOP_D = 0.0320   # 32.0mm 上端での奥行き（ポケットより上は絞って鰭にする）
# 角の側へ伸ばす帯。こちらは幅を増やさずに貼付面だけ増やせる。
PAD_TAB    = 0.0500   # 50.0mm 壁に沿って角の方へ伸ばす長さ
PAD_LAP    = 0.0040   # 4.0mm ウィングの壁面と重ねる量
# 帯だけ薄くする。部屋の入隅はきっちり 90° ではないので、そのぶんを帯のたわみで吸収する。
# 3mm から 2mm へ落とすと、鉛直軸まわりの曲げやすさが 3.4 倍になる。
PAD_TAB_T  = 0.0020   # 2.0mm 帯の厚み

# --- カメラ窓（外皮を貫通。カメラバーはここから外へ出る） ---
CAM_EDGE_RIM = 0.0040   # 4.0mm スマホ上端側に残す外皮リム
CAM_WIN_L    = 0.0340   # 34.0mm 窓の長さ（端末上端から 4〜38mm を覆う）
WIN_S_MIN    = 0.0030
WIN_S_MAX    = SLOPE_LEN + 0.0040   # 差し込み口まで抜く（窓の上に橋を架けない）
WIN_S_LEN    = WIN_S_MAX - WIN_S_MIN
WIN_S_CENTER = (WIN_S_MIN + WIN_S_MAX) / 2

# --- 差し込み口のテーパー（外皮側だけ広げて導入する） ---
TAPER_S0  = 0.0665
TAPER_LEN = 0.0140
TAPER_D   = 0.0012   # 入口で 1.2mm 逃がす（外皮は 1.3mm 残る）
TAPER_CUT = 0.0040   # カッターの厚み。テーパー面からスロット側へこれだけ抜く。
                     # 薄いと外皮の内面側だけ削れて外面が膜として残り、隙間ができる

# --- 指がかり（スマホの上端を表裏から摘まむ切り欠き） ---
GRIP_W  = 0.0460   # 46.0mm 幅（中央）
GRIP_S0 = 0.0635   # ここから上端まで外皮と裏板を落とす

# --- USB-C / スピーカーの逃げ（スマホ下端側の側壁を切り欠く） ---
USB_W = 0.0200   # 20.0mm 切り欠きの長さ（スロットを上る方向）
USB_T = 0.0170   # 17.0mm 厚み方向。側壁とウィングを貫いてケーブルを通す
USB_INTO = 0.0015  # 1.5mm スロット側へ食い込ませる量。0.5mm だと切り口が
                   # ノズル幅ほどの段差になり、印刷で潰れる
USB_S = STOPPER + SLOT_W / 2

# 貼付面（ウィングの外面）は座繰りを彫らず完全な平面にしてある。
# 彫るとテープの厚みばらつきで周囲の平面が先に壁へ当たり、かえって密着が落ちる。
