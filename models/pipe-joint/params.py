"""28mm パイプ（イレクター相当）用 5方向ジョイントの寸法定義。

すべて mm。ジオメトリ側で MM を掛けて Blender のメートルに変換する。

配置（Blender ワールド座標、パイプ軸 = X）:
    中央レール : 軸 (Y=0,        Z=0)
    左右レール : 軸 (Y=±SIDE_Y,  Z=SIDE_Z)      中央レールから芯間 SPAN
    左右の脚   : 軸 (Y=±SIDE_Y) の鉛直パイプ。上端が左右レールの下面に接する
"""

MM = 0.001

# --- パイプ ---
PIPE_OD = 28.0            # 実パイプ外径
CLEAR = 0.30              # 片側クリアランス（FDM のはめ合い）
BORE_D = PIPE_OD + 2 * CLEAR   # 28.6 内径

# --- 肉厚 ---
WALL = 4.0                     # スリーブ本体の肉厚
HUB_D = BORE_D + 2 * WALL      # 36.6 スリーブ外径
END_WALL = 1.2                 # テーパ端の肉厚
END_D = BORE_D + 2 * END_WALL  # 31.0 テーパ端の外径

# --- レール配置 ---
SPAN = 80.0               # 中央レール↔左右レールの芯間距離
SIDE_Y = 53.2             # 左右レールの Y オフセット（SPAN を維持したまま調整可）
SIDE_Z = 59.7             # 左右レールの Z オフセット
# hypot(53.2, 59.7) = 79.99 ≈ SPAN

# --- スリーブ（レールを掴む筒）---
SLEEVE_L = 56.0           # X 方向の全長 = パイプへの掴み代
TAPER_L = 14.0            # 端の S 字テーパ長。ここで HUB_D → END_D へ滑らかに落とす

# --- 脚のソケット ---
# 脚はレール本体には当てず、ソケット底の座面で受ける。
# パイプ同士だと丸面と平面の線接触になって座りが悪く、深さも決まらないため。
# 位置はすべて「左右レールの軸からの距離」で持つ（傾けても崩れない）。
LEG_FLOOR = 4.0                                  # 座面の厚み
LEG_TOP_D = BORE_D / 2 + LEG_FLOOR               # 18.3 レール軸→座面
LEG_BOT_D = 52.0                                 # レール軸→ソケット開口
LEG_ENGAGE = LEG_BOT_D - LEG_TOP_D               # 33.7 差し込み長

# 左右レールが水平でなく坂になっている場合の傾き（deg）。
# レール軸まわりではなく「レールの走る向き」の傾き。脚は鉛直のままなので、
# ジョイントのローカル座標では脚を Y 軸まわりに SLOPE_DEG だけ倒すことになる。
SLOPE_DEG = 0.0

# --- 斜材（中央スリーブ↔左右スリーブ）---
STRUT_W = 46.0            # X 方向の幅
STRUT_T = 13.0            # 厚み

# --- メッシュ品質 ---
SEG = 96                  # 回転体の分割数
TAPER_SEG = 14            # テーパ 1 本あたりの分割数

# --- 参照パイプ（フィット確認用。印刷対象ではない）---
REF_RAIL_L = 900.0        # 実パイプ長 90cm
REF_LEG_L = 400.0
