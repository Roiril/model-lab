"""28mm パイプ（イレクター相当）用 5方向ジョイントの寸法定義。

すべて mm。ジオメトリ側で MM を掛けて Blender のメートルに変換する。

配置（Blender ワールド座標、パイプ軸 = X）:
    中央レール : 軸 (Y=0,       Z=0)
    左右レール : 軸 (Y=±SIDE_Y, Z=SIDE_Z)
    左右の脚   : 軸 (Y=±SIDE_Y, X=LEG_X) の鉛直パイプ。上端は Z=LEG_TOP_Z の座面に当たる

ユーザー指定の寸法:
    中央レール↔左右レールの水平距離 = SIDE_Y = 80mm
    中央パイプ上端↔脚パイプ上端     = LEG_TOP_RISE = 30mm
    パイプ外径                       = PIPE_OD = 28mm

印刷の前提: +X を上にして一体で刷る。左右非対称。
    +X 端 : スリーブがパイプ面まで落ちる。上すぼまりなので無支持で出る。
            通行はこちら側から来る想定。両側から欲しければ 2 個を向かい合わせに使う
    -X 端 : 平ら。ベッドに丸ごと着く。角は BASE_ROUND ぶんだけ丸める
    柱と斜材は X_PRISM で止める。そこから上はスリーブだけが残る
    横倒しになる脚穴の天井だけティアドロップで自立させる
"""

import math

MM = 0.001

# --- パイプ ---
PIPE_OD = 28.0            # 実パイプ外径
CLEAR = 0.30              # 片側クリアランス（FDM のはめ合い）
BORE_D = PIPE_OD + 2 * CLEAR   # 28.6 内径

# --- 肉厚 ---
# レールのスリーブと脚のソケットで肉厚を分ける。
#   レール : パイプが貫通する襟なので、受けるのは主に輪の向きの力。3.0mm でノズル 0.4 の
#            7.5 本ぶんが並ぶ。外径 36.6 → 34.6
#   脚     : 側面ハブからぶら下がった片持ちで、曲げをまともに受ける。4.0mm のまま
RAIL_WALL = 3.0
LEG_WALL = 4.0
HUB_D = BORE_D + 2 * RAIL_WALL       # 34.6 レールのスリーブ外径
LEG_HUB_D = BORE_D + 2 * LEG_WALL    # 36.6 脚ソケットの幅

# --- 本体の X 方向（＝印刷の高さ）---
BODY_T = 54.0                  # X 全長 ＝ レールへの掴み代
TAPER_L = 16.0                 # +X 端でパイプ面まで落とすテーパ長
TIP_WALL = 0.4                 # テーパ先端に残す肉厚（ノズル 1 本ぶん）
TIP_D = BORE_D + 2 * TIP_WALL  # 29.4 → パイプ面からの段差 0.7mm
BASE_ROUND = 1.5               # -X 端の角丸
FILLET_R = 3.0                 # 接合部の R
FILLET_ANGLE = 25.0            # これより折れているエッジだけ R を付ける

X_TOP = BODY_T / 2             # +27.0
X_BOT = -BODY_T / 2            # -27.0
X_PRISM = X_TOP - TAPER_L      # +11.0 柱と斜材の上端

# --- 脚のソケット ---
# 脚はレール本体には当てず、ソケット底の座面で受ける。
# パイプ同士だと丸面と平面の線接触になって座りが悪く、深さも決まらないため。
# 座面は 4.0 → 9.0mm。実物のパイプが想定より短かったので、座面を 5mm 下げて
# 脚をそのぶん浅く咥え、継手が 5mm 高い位置に乗るようにした。継手そのものの寸法
# （SIDE_Y 80 / SIDE_Z 62.3 / 柱の下端 -11 / 弦）は動かない。
LEG_FLOOR = 9.0                                  # 座面の厚み（4.0 から 5mm 厚くした）
LEG_TOP_D = BORE_D / 2 + LEG_FLOOR               # 23.3 レール軸→座面（＝脚パイプの上端）
LEG_ENGAGE = 50.0                                # 柱ぶんの差し込み長（座面が 5mm 下がったぶん 55→50）
LEG_BOT_D = LEG_TOP_D + LEG_ENGAGE               # 73.3 レール軸→柱の下端（据え置き）
LEG_X = X_PRISM - LEG_HUB_D / 2                  # -7.3 脚穴の X 位置
# 脚穴は印刷時に横倒しになるので天井を 45 度の屋根にする。
# 屋根の頂点は軸から BORE_D/2*sqrt(2)=20.2 上。そこまで伸ばすと壁が無くなるので切る。
TEARDROP_TOP = X_PRISM - LEG_WALL                # +7.0 天井を切る高さ

# --- レール配置 ---
SIDE_Y = 80.0                            # 中央レール↔左右レールの水平距離（芯間）
# 座面を 5mm 厚くしたので、脚パイプの上端は 44.0 → 39.0 へ下がる（30 → 25）。
# SIDE_Z は 62.3 のまま動かない ＝ 継手の外形は変わらず、脚に対してだけ 5mm 上がる。
LEG_TOP_RISE = 25.0                      # 中央パイプの上端 → 脚パイプの上端
LEG_TOP_Z = PIPE_OD / 2 + LEG_TOP_RISE   # 39.0 脚パイプ上端の高さ
SIDE_Z = LEG_TOP_Z + LEG_TOP_D           # 62.3 左右レールの Z オフセット（芯間）
# 斜め芯間 hypot(80, 62.3) = 101.4

# 左右レールが坂になっている場合の傾き（deg）。
# ⚠ 0 以外にすると脚が X 方向の押し出しでなくなり、印刷の前提が崩れる。
SLOPE_DEG = 0.0

# --- M の下の弦（脚が内側へ倒れるのを止める）---
# 2 本の脚ソケットは側面ハブからぶら下がった片持ちで、下端どうしを繋ぐものが無い。
# そのため M は谷の頂点をちょうつがいにして閉じてしまう。柱の下端に 1 本渡すと
# 「柱 2 本 + 斜材 2 本 + 下の弦」で閉じたトラスになり、脚が内側へ倒れるには
# 弦が縮まないといけなくなる（圧縮になるので止まる）。
# 弦は全幅に通す。脚穴はあとから開けるので差し込み口は塞がらず、
# そのぶん差し込み長が 55 → 67mm へ伸びる（脚が傾く余地もここで減る）。
# ⚠ 柱へは面一で突き当てず、必ず食い込ませる。柱の下端 (z=-11) にぴったり合わせると
#   接触が厚み 0 の面になり、union が「non-manifold inputs」で丸ごと失敗する（実測）。
#   横も同じ理由で柱の側面より 1mm 内側に引く（重なった同一平面を作らない）。
# ⚠ 弦の実厚みは TIE_H。TIE_T は「柱の下端より下へ出る量」でしかない。
#   ここを取り違えて TIE_T で押し出していたので、弦は 15 ではなく 12mm で焼けていた
#   （下端 -21.5・柱への食い込み 1.5mm）。斜材が弦へ直接乗る形にしたので厚みを戻す。
TIE_T = 12.0                                  # 柱の下端から下へ出る高さ
TIE_LAP = 3.0                                 # 柱へ食い込ませる量
TIE_Z_BOT = SIDE_Z - LEG_BOT_D - TIE_T        # -23.0
TIE_Z_TOP = SIDE_Z - LEG_BOT_D + TIE_LAP      #  -8.0
TIE_H = TIE_Z_TOP - TIE_Z_BOT                 # 15.0 弦の実厚み（押し出しはこちらを使う）
TIE_Y = SIDE_Y + LEG_HUB_D / 2 - 1.0          # 97.3 左右の柱より 1mm 内側
TIE_ENGAGE = LEG_TOP_Z - TIE_Z_BOT            # 62.0 弦を通ったあとの実差し込み長

# --- 斜材（左右スリーブ → 下の弦）＝ M の谷 ---
# 斜材は中央スリーブで止めていた。谷に集まった力は襟の 3mm 壁を回り込んでから
# 弦へ降りるしかなく、三角形の角が中央の穴の上に浮いた状態だった。
# 下端を弦の肉の中まで延ばすと「柱・斜材・弦」が節点で閉じ、斜材は軸力だけで効く。
# 中央レールを避けるため、中央軸から STRUT_AXIS_R 離した直線へ振る。
# ⚠ 内側の面は襟へ STRUT_LAP だけ食い込ませる。面一にすると union が割れる（弦と同じ）
# ⚠⚠ 襟をかすめる浅い角度で刺すと bevel が壊れる（実測）。内側の面が襟の外周と作る角が
#   27.8 度だと非多様体が 257 本出て、そのあとの穴あけが丸ごと効かなくなった。
#   41 度まで立てると 0 本。STRUT_LAP はこの角度を決める値なので安易に下げない。
STRUT_T = 9.0                                 # 厚み（X 方向の幅は本体いっぱい）
STRUT_LAP = 4.3                               # 内側の面が中央スリーブへ食い込む量
STRUT_FACE_R = HUB_D / 2 - STRUT_LAP          # 13.0 中央軸 → 斜材の内側の面
STRUT_AXIS_R = STRUT_FACE_R + STRUT_T / 2     # 17.5 中央軸 → 斜材の中心線
STRUT_FOOT_Z = (TIE_Z_TOP + TIE_Z_BOT) / 2    # -15.5 下端は弦の厚みの真ん中で止める
STRUT_TOP_EXT = 12.0                          # 上端は左右レール軸より外へ出す
STRUT_CREASE = math.degrees(math.acos(STRUT_FACE_R / (HUB_D / 2)))   # 41.3 襟との交差角

assert STRUT_CREASE > 35.0, "斜材が襟を浅く撫でている。bevel が壊れる"
assert STRUT_FACE_R + STRUT_T / 2 > BORE_D / 2, "斜材が中央の穴に飲まれる"

# --- メッシュ品質 ---
SEG = 96                  # 円筒の分割数
TAPER_SEG = 16            # テーパの分割数
FILLET_SEG = 4            # 接合部 R の分割数

# --- 参照パイプ（フィット確認用。印刷対象ではない）---
REF_RAIL_L = 900.0        # 実パイプ長 90cm
REF_LEG_L = 400.0
