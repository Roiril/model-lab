# 28mm パイプの端に付ける Pixel 7a ホルダー（カメラを斜め下 45° へ）— 単位: m
#
# パイプの好きな位置に後付けできるよう、端から差し込む筒ではなく割りリングで抱く。
# つなぎ目の継手は跨がずに済むが、置く位置が継手と干渉しないかは寸法しだいなので、
# 継手の 3 つの値をパラメータにしてある。実測したらそこだけ直せばよい。
#
# 座標系（このファイルとジオメトリ側で共通）:
#   x … パイプ軸。x=0 がパイプの端で、+x が奥（継手から離れる向き）
#   h … カメラの視線。パイプから見て半径方向の外向き＋下向き 45°
#   s … スロットを上る向き（h と直交。外向き＋上向き）。差し込み口は上
import math

# --- パイプ（イレクター相当。models/pipe-* と同じ値） ---
PIPE_OD    = 0.0280
PIPE_CLEAR = 0.0003                        # 片側 0.3mm
BORE_D     = PIPE_OD + 2 * PIPE_CLEAR      # 28.6mm

# --- 継手（未計測。測ったらこの 3 つだけ直す） -------------------------------
# ビルド時に「継手との最小すきま」を印字するので、負になっていないか見ること。
JOINT_LEN = 0.0500   # 50.0mm パイプ端から継手が張り出す長さ
JOINT_R   = 0.0250   # 25.0mm 継手の外半径
JOINT_GAP = 0.0050   # 5.0mm  継手とクランプの間に空ける隙間

# --- 割りリング ---
RING_W    = 0.0200                     # 20.0mm リングの幅（軸方向）
RING_WALL = 0.0040                     # 4.0mm  リングの肉厚
RING_R    = BORE_D / 2 + RING_WALL     # 18.3mm 外半径
RING_DX   = 0.0900                     # 90.0mm リング 2 個の間隔
# 割りの隙間。ここが 0 だと本体と帯が先に当たってパイプを掴めない。
CLAMP_GAP = 0.0013                     # 1.3mm 片側（合わせて 2.6mm）
# 帯は 2 個のリングで別々に締める。1 枚で 2 個を同時に締めると片当たりする。
STRAP_ARC = 0.0035                     # 3.5mm 帯の肉厚（本体より薄くして先に馴染ませる）

# --- 耳とねじ（M4） ---
# 4mm では耳とナット座に足りない。耳は厚く、根元は大きく取る。
EAR_T   = 0.0090   # 9.0mm 耳の厚み（h 方向）
EAR_R   = 0.0250   # 25.0mm パイプ軸からねじ穴の中心まで
EAR_W   = 0.0150   # 15.0mm 耳の幅（s 方向）
SCREW_D = 0.0043   # 4.3mm M4 通し穴
NUT_AF  = 0.0074   # 7.4mm M4 ナットの二面幅 + 逃げ
NUT_T   = 0.0035   # 3.5mm ナットの厚み
# ナットは横から差し込む。締めるときに回り止めが要らない。
NUT_SLOT_W = 0.0074

# --- 姿勢 ---
CAM_DEPRESSION = 45.0                  # カメラの俯角
TILT_DEG       = 90.0 - CAM_DEPRESSION # 45.0° スマホ面の水平からの角度
D_BACK         = 0.0300                # 30.0mm パイプ軸からポケット裏面まで

# --- 背骨（リングとポケットを渡す板） ---
SPINE_T = 0.0090   # 9.0mm 厚み（s 方向）
SPINE_BITE = 0.0020  # 2.0mm 両側へ食い込ませる量

# --- テザー穴（1.9m の高さから落とさないための保険。結束バンドか紐を通す） ---
TETHER_D = 0.0045   # 4.5mm

# =========================================================================
# ここから下は据置版・壁掛け版と同じ実績寸法。触らない。
# =========================================================================
PHONE_L    = 0.1520   # 152.0mm 長辺（横向きに入れるのでパイプ軸と平行）
PHONE_W    = 0.0729   # 72.9mm 短辺（スロットを上る方向）
PHONE_T    = 0.0090   # 9.0mm 厚み（カメラバー部を除く）
PHONE_BUMP = 0.0011   # カメラバーの出っ張り 1.1mm（窓から外へ出す）

CLR_L = 0.0007
CLR_W = 0.0007
CLR_T = 0.0008

SLOT_L = PHONE_L + 2 * CLR_L   # 153.4mm
SLOT_W = PHONE_W + 2 * CLR_W   #  74.3mm
SLOT_T = PHONE_T + CLR_T       #   9.8mm

FRONT_SKIN = 0.0025   # 2.5mm 外皮（カメラ窓が開く。視線の側）
BACK_PLATE = 0.0030   # 3.0mm 裏板（画面側。パイプを向く）
SIDE_WALL  = 0.0035   # 3.5mm 側壁
STOPPER    = 0.0035   # 3.5mm スロット下端の受け

SHELL_TOTAL = FRONT_SKIN + SLOT_T + BACK_PLATE   # 15.3mm
SLOPE_LEN   = STOPPER + SLOT_W + 0.0008          # 78.6mm
SLOT_ENTRY  = 0.0600
MOUNT_W     = SLOT_L + 2 * SIDE_WALL             # 160.4mm

CAM_EDGE_RIM = 0.0040
CAM_WIN_L    = 0.0340
WIN_S_MIN    = 0.0030
WIN_S_MAX    = SLOPE_LEN + 0.0040
WIN_S_LEN    = WIN_S_MAX - WIN_S_MIN
WIN_S_CENTER = (WIN_S_MIN + WIN_S_MAX) / 2

TAPER_S0  = 0.0665
TAPER_LEN = 0.0140
TAPER_D   = 0.0012
TAPER_CUT = 0.0040

GRIP_W  = 0.0460
GRIP_S0 = 0.0635

USB_W = 0.0200
USB_T = 0.0170
USB_INTO = 0.0015
USB_S = STOPPER + SLOT_W / 2

# --- 抜け止め（45° は壁掛けの 50° より寝ているぶん、ぶつけたとき抜けやすい） ---
# 差し込み口の外皮側（スマホの背中側）に小さな山を作る。押し込むとき一度越える。
# 画面側には作らない。中央は指がかりの切り欠きが通るので、その外側に 2 か所。
LATCH_H = 0.0008   # 0.8mm スロットへ張り出す高さ（厚み方向の遊び 0.8mm を食う）
LATCH_L = 0.0120   # 12.0mm 1 か所の長さ
LATCH_X = 0.0300   # 30.0mm 中心からの距離（指がかり ±23mm とカメラ窓 +38.7mm を避ける）
LATCH_S = 0.0040   # 4.0mm 差し込み口の端から山の中心まで
LATCH_RUN = 0.0060  # 6.0mm 山の斜面の長さ（入る側をなだらかにする）
