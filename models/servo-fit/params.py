# servo-fit — サーボがはまるかだけ確かめる試し刷り（単位: mm）
#
# servo-arm の関節から「サーボを留める板（デッキ）」だけを取り出したもの。
# 板厚・クリアランス・穴の彫り方は servo-arm と同一なので、ここで合った値を
# そのまま models/servo-arm/params.py の同名の定数へ書き写せばよい。
#
# ⚠ 印刷の向きは servo-arm と同じ「板が立った状態」。寝かせて刷ると穴の出方
#   （橋渡し・1 層目のつぶれ）が変わり、試した意味が無くなる。この向きのまま刷る。

# ============================================================
# サーボ実寸（既定 = SG92R）。ノギスで測ってここを書き換える。
# 名前は servo-arm/params.py と同じにしてあるので、そのまま移せる。
# ============================================================
SERVO_BODY_L = 22.0            # 本体 長手（軸がずれている方向）
SERVO_BODY_W = 12.3            # 本体 幅
SERVO_BODY_H = 22.3            # 本体 高さ（底〜ケース上面・軸は含まない）
SERVO_SHAFT_OFFSET = 5.0       # 軸が本体長手中心からずれる量
SERVO_FLANGE_L = 32.2          # 羽根を含む全長
SERVO_FLANGE_W = 12.3          # 羽根の幅
SERVO_FLANGE_T = 2.2           # 羽根の厚み
SERVO_FLANGE_FROM_BOTTOM = 16.0  # 本体底〜羽根下面
SERVO_SCREW_SPACING = 28.84    # 取付ネジ穴のピッチ
SERVO_SCREW_PILOT = 1.7        # 取付ネジ下穴 ⌀（M2 セルフタップ想定）
SERVO_BOSS_DIA = 12.3          # ギアカバー座（大円柱）⌀
SERVO_BOSS_H = 4.6             # ギアカバー座の高さ（ケース上面から）
SERVO_SHAFT_DIA = 4.6          # 出力軸スプライン ⌀
SERVO_SHAFT_H = 3.6            # スプライン高さ（ギアカバー上面〜軸先端）
SERVO_TAB_HOLE = 3.0           # 羽根の穴 ⌀（ダミー表示用）

# ============================================================
# 試す寸法
# 1 枚に 1 つのクリアランスを割り当てて横に並べる。手前の点の数が番号で、
# 点 1 個がいちばんきつい（SERVO_CLR - CLR_STEP）。
# ============================================================
SERVO_CLR = 0.4       # はめ込みクリアランス 片側（並べる真ん中の値）
CLR_STEP = 0.1        # 1 枚ごとの刻み
N_VARIANTS = 3        # 並べる枚数（1 なら SERVO_CLR ちょうどの 1 枚だけ）

# ============================================================
# 板（servo-arm のデッキと同一）
# ============================================================
DECK_T = 7.0          # 板厚（羽根座を彫った残りがネジの効き代）
DECK_BACK = 29.0      # 軸からサーボ尻尾側への長さ
DECK_FRONT_R = 14.0   # 軸からギア側への張り出し
DECK_W = 22.0         # 板の幅（servo-arm の実効値。梁の高さに合わせて 22mm）

# 配線の通り道（尻尾側の穴の端を浅く広げる溝）。
# 線は本体底から約 4mm の高さで尻尾から出る。座れば板より下だが、差し込む途中で
# 必ず穴を通るので、この溝が無いとリボンを噛む。深さは取付ねじの下穴を食わない
# 範囲で自動的に頭打ちになる（SG92R なら約 2.0mm）
WIRE_NOTCH_W = 6.0    # 溝の幅（Y）。0 で無し
WIRE_NOTCH_D = 2.5    # 本体面からの深さ（希望値。ねじ穴に当たる手前で止まる）

# ============================================================
# 台（板を立てて刷るための足）
# ============================================================
FOOT_T = 5.0          # 足の厚み
FOOT_BACK = 20.0      # 板からサーボがぶら下がる側への張り出し
FOOT_FRONT = 9.0      # 板の反対側への張り出し
GAP = 6.0             # 板と板のすきま

# 番号の点（手前の縁に並ぶ突起）
PIP_DIA = 2.6         # 点の ⌀
PIP_H = 1.0           # 点の高さ
PIP_PITCH = 5.0       # 点の間隔

SHOW_SERVO = 1        # サーボ実体ダミーを重ねる（1=表示・プレビュー用）

