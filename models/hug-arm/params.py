PAD_GRIP = 1.2      # 袖が桁を掴む深さ（片側）
PAD_CLR = 0.15      # 袖の片側すきま（TPU なので詰める）
PAD_FROM = 0.45     # パッドを載せ始める位置（前腕の長さに対する割合）

# ============================================================
# 肩ブラケット（体側への取付）
# ============================================================
BRK_BACK_T = 5.0    # 体へ当てる背板の厚み
BRK_MARGIN = 5.0    # サーボまわりに残す縁
BRK_HOLE_DIA = 3.4  # 取付穴 ⌀（M3 ばか穴）
BRK_HOLE_PITCH = 30.0  # 取付穴のピッチ（Z）

# ============================================================
# 体への据え付け（プレビュー用。左右 2 本の位置関係を決める）
# ============================================================
SHOULDER_SPAN = 96.0   # 左右の肩軸の間隔（体の幅）
# ⚠ 腕は肩軸まわりに正面で開閉する。左右を同じ深さに付けると、閉じたとき同じ
#   平面で交差してぶつかる（実測で 105mm 重なった）。人が抱くときと同じで、
#   片方を前にずらして通す。前腕の板厚 9.5mm ＋ 逃げより大きくすること
