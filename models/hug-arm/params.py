# CATEGORY: ロボットアーム
# hug-arm — 抱きつくロボットの片腕（肩・肘の 2 自由度）— 寸法・定数
#
# servo-arm との違い（2026-09-03。参考モデル 3 点を読んで作り直した）:
#   servo-arm は二枚の頬板でサーボを丸ごと挟んでいた。挟む構造は軸方向から
#   組めないので、横入れのために軸方向へ 5.5mm の逃げが要り、関節幅が 50.1mm
#   になっていた。参考（アームサーボ / 左腕サーボ / サーボジンバル）はどれも
#   挟んでいない。サーボのギアカバー座のまわりに軸受けリングを立て、従動側は
#   そこへ片持ちで差すだけ。軸方向にまっすぐ入るので逃げが要らない。
#   結果、腕は 9.5mm の平板が 2 枚並ぶだけになる。
#
# 使うサーボ: M5Stack Servo Kit 180° を 2 個（servo-arm と同じ実測値）。
# 360° 版は連続回転で角度を保持できないので使わない。
#
# 単位はすべて mm（viewer の数値入力に出すため。model.py で m に直す）。
# 座標（リンクのローカル系）: X = 関節軸 / Y = 腕の伸びる向き / Z = 面内の上。
# 実装上の向き: 2 本の腕は前を向いた軸のまわりに正面で開閉する（下の MOUNT_* 参照）。

# ============================================================
# サーボ実寸（M5Stack 180° = SG92R 相当。2026-08-25 実測）
# 関節の幅・軸受けの高さ・ホーン結合面はすべてここから計算する
# ============================================================
SERVO_BODY_L = 22.0            # 本体 長手（軸がずれている方向）
SERVO_BODY_W = 12.3            # 本体 幅
SERVO_BODY_H = 22.3            # 本体 高さ（底〜ケース上面・軸は含まない）
SERVO_SHAFT_OFFSET = 5.0       # 軸が本体長手中心からずれる量
SERVO_FLANGE_L = 32.2          # 羽根を含む全長
SERVO_FLANGE_W = 12.3          # 羽根の幅
SERVO_FLANGE_T = 2.2           # 羽根の厚み
SERVO_FLANGE_FROM_BOTTOM = 16.0  # 本体底〜羽根下面
SERVO_SCREW_SPACING = 28.84    # 取付ネジ穴のピッチ
SERVO_SCREW_PILOT = 1.7        # 取付ネジ下穴 ⌀（M2 セルフタップ想定）
SERVO_BOSS_DIA = 12.3          # ギアカバー座（大円柱）⌀ … これが軸受けの内側になる
SERVO_BOSS_H = 4.6             # ギアカバー座の高さ（ケース上面から）
SERVO_SHAFT_DIA = 4.6          # 出力軸スプライン ⌀
SERVO_SHAFT_H = 3.6            # スプライン高さ（ギアカバー上面〜軸先端）

# ============================================================
# サーボホーン（付属の十字ホーン）
# ⚠ 長腕をニッパで 24mm（片側 12mm）に詰めてから使う。実物は 35mm ある。
#   詰めない場合はここを 35 に戻す。軸受けの径とハブが自動で太る（⌀43 になる）
#
# 十字の溝は彫らない。軸受け穴をホーンが丸ごと通る径にして、そこへ落とす。
# 溝を彫る方式は、溝を穴の底からしか彫れず、腕が軸方向に通る道が無くなる
# （2026-09-03 に共通体積で発覚）。穴 1 つで済む方が形も単純になる
# ============================================================
HORN_SPAN_LONG = 24.0          # 長腕の全長（端〜端）。詰めた後の値
HORN_SPAN_SHORT = 17.0         # 短腕の全長
HORN_ARM_W_LONG = 6.8          # 長腕の幅
HORN_ARM_W_SHORT = 3.6         # 短腕の幅
HORN_HUB_DIA = 7.0             # 中央ハブ ⌀
HORN_T = 2.0                   # 腕板の厚み（＝受け溝の深さ）
HORN_SCREW_DIA = 2.4           # センタービス ⌀
HORN_ARM_SCREW_R = 9.0         # 軸中心から長穴の中央までの距離
                               # ⚠ 軸受け穴の縁より外に置くと、ねじの外側に肉が
                               #   ほとんど残らない。穴の中（＝ホーンの真上）へ置く
HORN_ARM_SCREW_DIA = 1.9       # 長穴の幅 ⌀（M2 セルフタップ）
HORN_ARM_SLOT = 6.0            # 長穴の長さ（腕の向き）… 個体差のある穴位置を吸収

# ============================================================
# サーボの性能（載せられる重さと回せる角度を決める値）
# ============================================================
SERVO_STALL_KGCM = 1.8   # 定格ストールトルク @6.0V
SERVO_DUTY = 0.333       # 連続で効かせてよい割合。定格の 1/3 が目安
SERVO_MASS_G = 9.0       # サーボ 1 個
HORN_MASS_G = 1.5        # ホーン 1 枚
PLA_DENSITY = 0.55       # g/cm3（20% infill の実効密度）

# 0° = 腕が真横（体から離れて水平）／+ が体の前へ閉じる向き。
# 抱きつくので「閉じ切り」側を広く、開き側は体に当たる手前で止める
SHOULDER_WINDOW = (-20.0, 160.0)
ELBOW_WINDOW = (0.0, 150.0)
SERVO_SPLINE_TEETH = 20        # ホーンは 18° 刻みでしか差し替えられない

# ============================================================
# 関節モジュール（肩・肘 共通）
# 駆動側 = サーボを持つ方。従動側 = ホーンで回される方。
# 従動側は「軸受けリングに差してホーンへねじ止め」だけ。挟まない
# ============================================================
DECK_T = 4.5        # サーボを留める板の厚み。M2 セルフタップの効き代
                    # ⚠ ギアカバー座（4.6mm）より厚くすると座が板に埋まって
                    #   軸受けが成立しない。model.py が上限で頭打ちにする
JOURNAL_D = 18.0    # 軸受けリングの外径。従動側はこの外周に乗る
                    # ⚠ ホーンがこの穴を通って奥へ落ちる必要があるので、
                    #   model.py が「ホーンの角が回る径」まで自動で広げる
JOURNAL_CLR = 0.35  # 軸受けの片側すきま（回る面なので広め）
BOSS_CLR = 0.3      # リング内径 ↔ ギアカバー座 の片側すきま
HORN_CLR = 0.2      # ホーン溝の片側すきま
LEDGE_T = 3.0       # ホーン溝の上に残す肉。ここへ長穴のねじが効く
HUB_WALL = 3.2      # 軸受け穴のまわりに残す肉 → ハブ半径 = 軸受け半径 + これ
SERVO_CLR = 0.4     # サーボはめ込みクリアランス（片側）

# ============================================================
# リンク（腕）
# ⚠ 長さは重さより効く。servo-arm の実測では 100+100mm で肩トルクの 54% を
#   自重が食っていた。抱きつくだけで物は持たないので、短く細くする
#
# 桁は一定幅・一定厚み。参考（アームサーボ / サーボジンバル）の腕はどれも
# 一定幅の板で、丸穴を並べたものは 1 つも無い。抜くときはスポークや角窓の
# ような大きな構造開口で抜いている
# ============================================================
L1 = 78.0           # 肩軸 → 肘軸
L2 = 90.0           # 肘軸 → 腕の先端
PLATE_T = 9.5       # 平板の厚み（X）… model.py が軸受け＋溝＋肉から最小値を出す
BEAM_W = 20.0       # 桁の幅（Z）。全長で一定
                    # ⚠ 肘のサーボ穴（13.1mm）の両脇に肉を残す幅が要る
BEAM_TAPER = 0.20   # ハブから桁幅へ絞る区間（リンク長に対する割合）

# 前腕は内側へ曲げる。まっすぐだと点でしか当たらず、抱きつく形にならない
FORE_CURL = 55.0    # 前腕全体の曲がり（度）。+ が抱き込む向き
FORE_NODES = 5      # 曲げを近似する節点の数

# 桁の中抜き。面内の曲げでは中央の肉は効かないので、真ん中を 1 本だけ抜く。
# 配線と結束バンドの通り道も兼ねる
SLOT = 1            # 1 で抜く
SLOT_RAIL = 4.5     # 両脇に残す桁（片側）
SLOT_MARGIN = 4.0   # ハブ（や先端）の縁から溝までの距離
SLOT_MIN = 35.0     # これより短くしか取れないなら抜かない
                    # 上腕は両端のハブと肘のサーボ座でほぼ埋まっていて 27mm しか
                    # 取れない。短い溝を無理に入れるのは理由の無い穴なので開けない

# ============================================================
# 当たり面（TPU パッド）
# 硬い PLA のまま抱きつくと、サーボは 1.8kgf·cm を出し続けるので相手に食い込む。
# 前腕の内側の縁に TPU の袖をかぶせて、当たりを面で受けて逃がす
# ============================================================
PAD = 1             # 1 でパッドを作る
