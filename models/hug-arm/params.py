                       # ⚠ 0 以外にすると左右の振れる面が平行でなくなり、
                       #   前後にずらしても中央で当たることがある（下の [pair] で確認）
SHOW_PAIR = 1          # 1 でプレビューに反対側の腕も出す

# ============================================================
