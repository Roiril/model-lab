"""28mm パイプの脚を床に固定するベース（フランジ足）の寸法定義。

すべて mm。ローカル座標: 原点は底面の中心、+Z が上（パイプの向き）。

ユーザー指定:
    フランジの厚み            = FLANGE_T = 5mm
    パイプの下端 → 底面まで   = SEAT_Z   = 30mm
    ねじ穴 4mm を 4 方向に

印刷の前提: この向きのまま（底面をベッドに置いて）刷る。
    - 底面が丸ごと着く。ねじ穴もソケットも縦向きなので無支持
    - 台座は上へ行くほど細るだけなので、外側にオーバーハングが無い
"""

MM = 0.001

# --- パイプ ---
PIPE_OD = 28.0
CLEAR = 0.30
BORE_D = PIPE_OD + 2 * CLEAR       # 28.6

# --- ソケット（パイプを差し込む筒）---
WALL = 4.0
BOSS_R = BORE_D / 2 + WALL         # 18.3 外径 36.6
SEAT_Z = 30.0                      # パイプの下端の高さ ＝ 底面からの距離
SOCKET_DEPTH = 55.0                # 差し込み長（他の部品と揃える）
BOSS_TOP = SEAT_Z + SOCKET_DEPTH   # 85.0 全高
MOUTH_TAPER = 12.0                 # 口元で絞る長さ
TIP_WALL = 1.0
TIP_R = BORE_D / 2 + TIP_WALL      # 15.3 → パイプ面からの段差 1.3mm

# --- フランジ（床に留める板）---
FLANGE_T = 5.0                     # 板厚
DISC_R = 32.0                      # 中央の円の半径
LOBE_R = 12.0                      # ねじ穴まわりの丸の半径
BOLT_R = 38.0                      # ねじ穴の中心までの距離（外形は 38+12=50 → 全幅 100）
SCREW_D = 4.5                      # M4 のバカ穴。印刷で縮むぶんを見て 4.5 で描く
SCREW_CHAMFER = 0.8                # 穴の口の面取り

# --- 台座（フランジ → ソケットのつなぎ）---
# フランジ上面に平らな縁を DISC_R - CONE_BASE_R = 8mm 残す。ここが 2mm しかないと
# 両側の R が食い合って Bevel が発散する（Blender 5.1 で実測）。
CONE_BASE_R = 24.0                 # フランジ上面での半径
# CONE は SEAT_Z までで BOSS_R に収束する。傾きは最大 37 度で無支持

# --- 仕上げ ---
FILLET_R = 3.0
FILLET_ANGLE = 25.0
FILLET_SEG = 4
BASE_ROUND = 1.5                   # 底の角丸（後で平らに切る分）

# --- メッシュ品質 ---
SEG = 96
CONE_SEG = 24

# --- 参照パイプ（フィット確認用。印刷対象ではない）---
REF_LEN = 200.0
