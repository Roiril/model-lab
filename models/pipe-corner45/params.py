JOINT_POST = 0.0450   # 45.0mm 角から縦柱に沿って張り出す長さ
JOINT_GAP  = 0.0040   # 4.0mm  継手との隙間

# --- 割りリング（レール用・柱用で同じ寸法。帯は 1 種類で兼用） ---
RING_W    = 0.0240                     # 24.0mm リングの幅（軸方向）
RING_WALL = 0.0040                     # 4.0mm  リングの肉厚
RING_R    = BORE_D / 2 + RING_WALL     # 18.3mm 外半径
CLAMP_GAP = 0.0013                     # 1.3mm 割りの片側の隙間（0 だと締まらない）
STRAP_ARC = 0.0035                     # 3.5mm 帯の肉厚（本体より薄くして先に馴染ませる）

# --- 耳とねじ（M4） ---
EAR_T   = 0.0090   # 9.0mm 耳の厚み
EAR_R   = 0.0250   # 25.0mm 軸からねじ穴の中心まで
EAR_W   = 0.0150   # 15.0mm 耳の幅
SCREW_D = 0.0043   # 4.3mm M4 通し穴
NUT_AF  = 0.0074   # 7.4mm M4 ナットの二面幅 + 逃げ
NUT_T   = 0.0035   # 3.5mm ナットの厚み
NUT_SLOT_W = 0.0074   # ナットは横から差し込む

# --- 姿勢と位置（Blender に置かれたキューブに合わせた） ---
CAM_DEPRESSION = 45.0   # カメラの俯角
P_BACK = 0.0660   # 66.0mm 角からポケット裏面まで（視線方向に測る）
                  # キューブの中心はレール軸から 67mm。ここを詰めると縦柱に当たる
Y_PH   = 0.0520   # 52.0mm ポケットの中心を角からレール方向へずらす量

# --- 板（リングとポケットを渡す） ---
WEB_T  = 0.0090   # 9.0mm 板の厚み
WEB_BITE = 0.0020  # 2.0mm 両側へ食い込ませる量

# --- テザー穴（1.9m の高さから落とさないための保険） ---
TETHER_D = 0.0045

# =========================================================================
# ここから下は据置版・壁掛け版と同じ実績寸法。触らない。
# =========================================================================
PHONE_L    = 0.1520   # 152.0mm 長辺（水平レールと平行）
