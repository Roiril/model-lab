# 28mm パイプの入隅（縦柱＋水平レール）に付ける Pixel 7a ホルダー — 単位: m
#
# pixel7a-corner45（壁の入隅に両面テープ）を、パイプ 2 本で掴む形に置き換えたもの。
# 壁の版は首を 45° 振っていたが、こちらは振らない。スマホの長辺は水平レールと平行で、
# カメラはレールの半径方向・外向きに 45° 下を向く。
#
# 座標系（角＝2 本の軸の交点を原点にする）:
#   x … 外向き（フレームの外側）      y … 水平レールに沿って奥（角から離れる）
#   z … 上向き。縦柱は z<0 側へ伸びる
#   h … カメラの視線 ( cos45, 0, -sin45)   s … スロットを上る向き ( sin45, 0, cos45)
#
# パイプ 2 本を掴むので、片方だけのときと違って摩擦に頼らない。
# レールのリングが縦軸まわりの回転を止め、柱のリングがレール軸まわりの回転を止める。
import math

# --- パイプ（イレクター相当。models/pipe-* と同じ値） ---
PIPE_OD    = 0.0280
PIPE_CLEAR = 0.0003                        # 片側 0.3mm
BORE_D     = PIPE_OD + 2 * PIPE_CLEAR      # 28.6mm
# 縦柱側は 2 本を同時に掴むぶん、直角の誤差を逃がす余地を持たせる
POST_EXTRA = 0.0004                        # 0.4mm 縦柱のボアだけ広げる

# --- 継手（未計測。測ったらこの 4 つだけ直す） -------------------------------
# 角にある継手が占める空間を、2 本の円柱として全部品から彫る。
# ビルド時に部品ごとの「継手すきま」と「実機と継手のすきま」を印字する。
JOINT_R    = 0.0300   # 30.0mm 継手の外半径
