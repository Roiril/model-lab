"""足ジョイント 2 個に上からかぶせて、脚パイプの芯間を M 字ジョイントと揃える板。

すべて mm。ローカル座標: 板の中心が原点、+Z が上。穴の中心は x = ±SPAN/2。
この向きのまま（板を寝かせて）刷る。平らなので支持材は要らない。

なぜ要るか:
    脚パイプは上端を M 字ジョイントの脚ソケット（芯間 160mm）に咥えられる。
    下端の足ジョイントは床に貼るだけなので芯間が決まらず、パイプが傾く。
    上と同じ 160mm を下でも与えれば、パイプは 2 点で拘束されて垂直に立つ。

かぶせ方:
    パイプを差す前でも後でもよい。穴は Φ37.1 でパイプ（Φ28）より大きいので、
    上から通して落とすとソケットの外周（Φ36.6）を掴み、リブの頂点で止まる。
"""

MM = 0.001

# --- 合わせる相手 ---
# models/pipe-joint/params.py の SIDE_Y = 80.0（芯間はその 2 倍）
SPAN = 160.0
# models/pipe-foot/params.py の BOSS_R = 18.3（ソケット外径）
BOSS_D = 36.6
# 片側のすきま。落とし込むので締まり嵌めにはしない。
# 0.25 なら芯間の誤差は最大 ±0.5mm ＝ 900mm の脚で 0.03 度。無視できる
CLEAR = 0.25
HOLE_D = BOSS_D + 2 * CLEAR            # 37.1

# --- 板 ---
RIM = 11.45                            # 穴のまわりに残す肉
PLATE_W = HOLE_D + 2 * RIM             #  60.0 短辺
PLATE_L = SPAN + PLATE_W               # 220.0 長辺（穴の外側の肉も RIM と同じになる）
PLATE_T = 8.0                          # 厚み。そのままソケットを掴む長さになる
CORNER_R = 10.0                        # 角丸
EDGE_R = 1.2                           # 外周と穴の口の面取り

# --- メッシュ品質 ---
SEG = 96                               # 穴の分割数
CORNER_SEG = 12                        # 角丸の分割数
FILLET_SEG = 3
FILLET_ANGLE = 30.0

# --- 参照（フィット確認用。印刷対象ではない）---
FOOT_SEAT_Z = 47.3                     # 足ジョイントのリブに当たって止まる高さ
