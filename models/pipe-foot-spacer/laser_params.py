"""芯間合わせ板をレーザーカッターで作るときの寸法定義。

すべて mm。3D 版（params.py）から変えたのは厚みの作り方だけで、
外形・穴径・芯間はそのまま引き継ぐ。

厚み 8mm を 3mm 板でどう出すか:
    3 枚重ねて 9mm。8 → 9mm はソケットを掴む長さが 1mm 伸びるだけで、
    止まる高さ（足ジョイントのリブ天端 z=47.3）も、その上に残る
    ソケットの直胴（z=73 まで）も変わらない。2 枚 6mm だと掴みが浅く、
    パイプの傾きに対する腕の長さが 3/4 になるので 3 枚にする。

3 枚をどう揃えるか:
    穴がずれるとその分だけ実効の穴径が縮む。0.5mm ずれると Φ36.6 の
    ソケットに対して隙間が消えて入らない。だから重ねるときの位置決めを
    材料任せにせず、同じ板から切った角棒を刺して合わせる。

    角棒の断面は「切り幅方向 3.0mm（レーザーなので正確）」×「板厚方向
    （アクリルの実厚は公称 ±0.2〜0.4 ばらつく）」。そこで受け穴は
    切り幅方向だけを詰め、板厚方向は逃がした長穴にする。
    上 2 本で X を、下 2 本で Y を決める配置にすれば、板厚が何 mm でも
    3 枚は一意に揃う。
"""

import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "../../lib"))

from params import SPAN, HOLE_D, PLATE_W, PLATE_L, PLATE_T, CORNER_R  # noqa: F401
import laser_core as lc

# --- 素材とレーザー ---
SHEET_T = lc.MAT_T                 # 3.0 板厚
KERF = lc.KERF                     # 0.1 ビームで溶ける幅（切り線の両側に 0.05 ずつ）
LAYERS = 3                         # 3.0 x 3 = 9.0mm（3D 版は 8.0mm）
STACK_T = SHEET_T * LAYERS         # 9.0

# --- 位置決めの角棒 ---
PIN_N = 4                          # 使う本数
PIN_SPARE = 2                      # 予備（小物はよく飛ぶ）
PIN_X = 35.0                       # 角棒の中心。Φ37.1 の穴からも外周からも離れている
PIN_Y = 18.0
PIN_FIT = 0.10                     # 詰める側のすきま（切り幅方向）
PIN_SLOP = 0.6                     # 逃がす側の追加（板厚のばらつきを吸う）
PIN_TIGHT = 3.0                    # 詰める側の公称。棒の切り幅もこれ
PIN_LEN = STACK_T - 0.4            # 8.6 重ねた厚みより短くして頭を出さない

# --- 板取り ---
GAP = 6.0                          # パーツ間のすきま
MARGIN = 5.0                       # 板の縁からのすきま（write_svg 側の余白）
