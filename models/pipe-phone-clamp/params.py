# =========================================================================
# つっかえ棒（縦の柱へ渡すブレース）— 角のジョイント版では使わない
# =========================================================================
# レールのクランプ 1 個だけだと、パイプ軸まわりに回る自由度が摩擦でしか止まっていない。
# 縦の柱にもう 1 個クランプを付け、両者を 1 本の棒で結ぶと、その自由度が形で止まる。
#
# ただし 2 本のパイプにまたがる部品は「継手の遊びぶん寸法が合わない」で入らなくなる。
# なので棒の両端は 1 本ずつのボルトで留める（＝ピン結合。角度は現物合わせで決まる）。
# 片方の穴は長穴にして、長さの誤差 ±3mm を組むときに吸収する。
#
# 継手の占有（ユーザー実測）: 角から横方向 80mm、縦方向 50mm。
# → 柱側の自由なパイプは z < 916.6mm。リング上端 911mm はその 5.6mm 下。
