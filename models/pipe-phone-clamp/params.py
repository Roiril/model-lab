# Φ28 パイプに後付けする Pixel 7a ホルダー — 寸法（単位: m。コメントは mm）
#
# 3 部品 + M4×4 本。パイプは組んだ後なので、端から通す筒は使えない。半割りで抱く。
#   M_saddle … パイプを抱く半分。腕と合わせ面（パッド）まで一体
#   M_strap  … 反対側の半分。M4×2 で saddle と締める
#   M_cradle … スマホのポケット。背中のボスをパッドへ M4×2 で留める
#
# 座標系は 2 つ。どちらも「その向きのまま印刷する」向きで定義してある。
#   K … クランプ側。z = パイプ軸、x = 腕が出る半径方向、y = z×x
#        → z を上にして置くとリングが寝る。腕は水平に伸びる。支持材が要らない
#   C … ポケット側。原点 = スマホの中心、x = カメラの視線（前）、
#        y = スマホの長辺、z = スロットを上る向き（差し込み口は +z）
#        → z を上にして置くと立つ。壁が全部垂直になり、橋が 1 か所も無い
import math

# =========================================================================
# 実物の寸法
# =========================================================================
PIPE_OD  = 0.0280                      # 28.0mm イレクター相当
PIPE_CLR = 0.0003                      # 片側 0.3mm
BORE_R   = PIPE_OD / 2 + PIPE_CLR      # 14.3mm ボア半径

# Pixel 7a（据置版・壁掛け版で実機が入った値。触らない）
PHONE_L    = 0.1520   # 152.0mm 長辺（横向きに入れる）
PHONE_W    = 0.0729   #  72.9mm 短辺（スロットを上る向き）
PHONE_T    = 0.0090   #   9.0mm 厚み（カメラバーを除く）
PHONE_BUMP = 0.0011   #   1.1mm カメラバーの出っ張り（窓から外へ出る）

CLR_L = 0.0007
CLR_W = 0.0007
CLR_T = 0.0008
SLOT_L = PHONE_L + 2 * CLR_L   # 153.4mm
SLOT_W = PHONE_W + 2 * CLR_W   #  74.3mm
SLOT_T = PHONE_T + CLR_T       #   9.8mm

# =========================================================================
# ポケット（C 座標）
# =========================================================================
# 前面は窓ではなく枠にする。カメラを外へ向けても、画面を外へ向けても同じ器で足りる。
FRONT_RIM  = 0.0030   # 3.0mm 枠の厚み
BACK_PLATE = 0.0030   # 3.0mm 裏板（腕が付く側）
SIDE_WALL  = 0.0035   # 3.5mm 側壁
STOPPER    = 0.0040   # 4.0mm スロット下端の受け
BORDER     = 0.0080   # 8.0mm 枠の幅（スロットの縁から内側へ）

SHELL_Y = SLOT_L + 2 * SIDE_WALL          # 160.4mm 全幅
X_BACK  = -(SLOT_T / 2 + BACK_PLATE)      #  -7.9mm 背面
X_FRONT = +(SLOT_T / 2 + FRONT_RIM)       #  +7.9mm 前面
Z_TOP   = +SLOT_W / 2                     # +37.15mm 差し込み口（スロット上端と面一）
Z_BOT   = -(SLOT_W / 2 + STOPPER)         # -41.15mm 底

# 背中のボス（腕のパッドを受ける。ナットを横から差す厚みが要る）
BOSS_T = 0.0100   # 10.0mm
BOSS_Y = 0.0640   # 64.0mm
BOSS_Z = 0.0360   # 36.0mm

USB_W    = 0.0200   # 20.0mm 底の切り欠き（挿したまま吊れる）
TETHER_R = 0.0020   #  4.0mm 落下保険の紐穴（ボスを長辺方向に貫く）
BEVEL    = 0.0008   #  0.8mm 外周の面取り

# =========================================================================
# クランプ（K 座標）
# =========================================================================
RING_WALL = 0.0045                  #  4.5mm リングの肉厚
RING_R    = BORE_R + RING_WALL      # 18.8mm 外半径
RING_W    = 0.0260                  # 26.0mm 幅（パイプ軸方向）

# 半割りの合わせ面は突き当てない。突き当たると先に面が当たってパイプを掴めない。
SPLIT_GAP = 0.0015                  #  1.5mm 両半分の隙間（片側 0.75mm）

EAR_T  = 0.0080   #  8.0mm 耳の厚み（片側。ボルトの積み上げは 8+1.5+8）
# 耳の内端。ボアぴったり（14.3mm）にすると耳の面がボアの円筒に接する。接する合わせは
# EXACT でも薄片が出るので、0.8mm 外へ逃がす。逃がした分はリングの肉が埋める。
EAR_Y0 = BORE_R + 0.0008
EAR_Y1 = 0.0300   # 30.0mm 耳の外端
BOLT_Y = 0.0220   # 22.0mm ボルト軸（ボアの外 19.8mm、耳の端まで 5.8mm）

ARM_H = 0.0180   # 18.0mm 腕の高さ（Ky）
ARM_W = 0.0260   # 26.0mm 腕の幅（Kz。リングと同じ）

PAD_T      = 0.0080   #  8.0mm パッドの厚み
PAD_Y      = 0.0600   # 60.0mm
PAD_Z      = 0.0340   # 34.0mm
PAD_BOLT_Y = 0.0220   # 22.0mm パッドのボルト間隔の半分

# M4
BOLT_R = 0.0022   # 4.4mm 通し穴
NUT_AF = 0.0072   # 7.2mm ナットの二面幅（軽い圧入）
NUT_T  = 0.0034   # 3.4mm ナットの厚み
CB_R   = 0.0038   # 7.6mm 頭の座ぐり
CB_D   = 0.0030   # 3.0mm 座ぐりの深さ

# =========================================================================
# 据え付ける姿勢（Blender でユーザーが置いた板 Cube.005 と同じ）
# live.py は板があれば実物から読む。ここの値は板が無いときの控え。
# =========================================================================
PLATE_EULER_DEG = (0.0, 45.0, 45.0)                 # XYZ オイラー
PHONE_CENTER    = (0.5879, -0.8278, 0.9265)         # スマホの中心（ワールド, m）
RAIL_POINT      = (0.4800, 0.0000, 0.9666)          # レール B の軸上の 1 点
RAIL_DIR        = (0.0, 1.0, 0.0)                   # レール B の軸の向き
