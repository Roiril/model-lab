STRUT_W     = 0.0240   # 24.0mm 棒の幅
STRUT_END   = 0.0130   # 13.0mm 穴の中心から棒の端まで
STRUT_SLOT  = 0.0030   # ±3.0mm 長穴の遊び（継手の遊びを組むときに吸収する）
POST_HOLE_R = 0.0400   # 40.0mm 柱の軸からラグの穴まで（水平距離）
LUG_W       = 0.0260   # 26.0mm ラグの幅（リングと同じ）
LUG_DEPTH   = 0.0400   # 40.0mm ラグを平面からリングへ向けて伸ばす長さ
CRADLE_LUG_R = 0.015   # 15.0mm ポケットのボス面から、棒の向きを測る基準点まで
# ポケット側は水平のラグを付けない。ポケットは 45° 傾いているので、水平の板を足すと
# それが造形板側へ 20mm はみ出し、殻の底 3800mm2 が宙に浮く（実測）。かわりに棒の端を
