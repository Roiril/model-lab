# Φ28 パイプに付ける Pixel 7a ホルダー — 寸法（単位: m。コメントは mm）
#
# ⭐ 現行版は 2 部品・ねじ無し（M_corner と M_cradle。舌と穴で位置を決めて接着する）。
#   1 部品にすると、どの向きに置いても造形板に着く平らな面が無く（実測 接地 0mm2）、
#   ポケットの底が 54mm 宙に浮いてスパゲッティになる。だから印刷の都合で 2 個に割る。
#   組み方: 継手を外す → レールを抜く → レールの端から本体を通す → 本体ごと下ろして
#   柱の上端へ被せる → レールの向こう端を元の継手へ戻す → ポケットを接着。
#
# 座標系。C は「その向きのまま印刷する」向きで定義してある。
#   C … ポケット側。原点 = スマホの中心、x = カメラの視線（前）、
#        y = スマホの長辺、z = スロットを上る向き（差し込み口は +z）
#        → z を上にして立てると壁が全部垂直になる。この向きで印刷する
#   fR / fQ … 各パイプのリング。z = パイプ軸、x = C の z をその軸へ射影した向き
#        （＝ボアの天井の切妻を向ける方向。印刷の上向きに合わせてある）
import math

# =========================================================================
# 実物の寸法
# =========================================================================
PIPE_OD  = 0.0280                      # 28.0mm イレクター相当
PIPE_CLR = 0.0003                      # 片側 0.3mm
BORE_R   = PIPE_OD / 2 + PIPE_CLR      # 14.3mm ボア半径

# Pixel 7a（据置版・壁掛け版で実機が入った値。触らない）
PHONE_L    = 0.1520   # 152.0mm 長辺（横向きに入れる）
PHONE_W    = 0.0729   #  72.9mm 短辺（スロットを上る向き）
PHONE_T    = 0.0090   #   9.0mm 厚み（カメラバーを除く）
PHONE_BUMP = 0.0011   #   1.1mm カメラバーの出っ張り（窓から外へ出る）

CLR_L = 0.0007
CLR_W = 0.0007
CLR_T = 0.0008
SLOT_L = PHONE_L + 2 * CLR_L   # 153.4mm
SLOT_W = PHONE_W + 2 * CLR_W   #  74.3mm
SLOT_T = PHONE_T + CLR_T       #   9.8mm

# =========================================================================
# ポケット（C 座標）
# =========================================================================
# ⚠ ここから下の差し込み側は models/pixel7a-stand（exports/pixel7a-stand.stl として
# 実機で入ることを確認済み）と同じ寸法・同じ形にしてある。勝手に変えない。
FRONT_SKIN = 0.0025   # 2.5mm 外皮（この裏にスマホ背面が接する。カメラ窓が開く）
BACK_PLATE = 0.0030   # 3.0mm 裏板（画面側。腕とつっかえ棒が付く）
SIDE_WALL  = 0.0035   # 3.5mm 側壁
STOPPER    = 0.0035   # 3.5mm スロット下端の受け（ここでスマホが止まる）

SLOPE_LEN  = STOPPER + SLOT_W + 0.0008    # 78.6mm 斜面の長さ（上端に 0.8mm 残る）
SLOT_ENTRY = 0.0600                       # 差し込み口を抜くためのカッター延長
S_MID      = STOPPER + SLOT_W / 2         # 40.65mm 斜面座標 s の、スマホ中心の位置
                                          #   → C_z = s - S_MID で読み替える

SHELL_Y = SLOT_L + 2 * SIDE_WALL          # 160.4mm 全幅
X_BACK  = -(SLOT_T / 2 + BACK_PLATE)      #  -7.9mm 背面
X_FRONT = +(SLOT_T / 2 + FRONT_SKIN)      #  +7.4mm 前面（外皮の外側）
Z_TOP   = SLOPE_LEN - S_MID               # +37.95mm 差し込み口
Z_BOT   = -S_MID                          # -40.65mm 底

# カメラ窓（外皮を貫通。カメラバーはここから外へ出る）
CAM_EDGE_RIM = 0.0040   # 4.0mm スマホ上端側に残す外皮リム
CAM_WIN_L    = 0.0340   # 34.0mm 窓の長さ
WIN_S_MIN    = 0.0030
WIN_S_MAX    = SLOPE_LEN + 0.0040   # 上まで抜く（窓の上に橋を架けない）

# 差し込み口のテーパー（外皮の内面だけ広げて導入する）
TAPER_S0  = 0.0660
TAPER_LEN = 0.0140
TAPER_D   = 0.0012   # 入口で 1.2mm 逃がす（外皮は 1.3mm 残る）

# 指がかり（スマホの上端を表裏から摘まむ切り欠き）
GRIP_W  = 0.0460
GRIP_S0 = 0.0630

# USB-C / スピーカーの逃げ（スマホ下端側の側壁を切り欠く）
USB_W = 0.0200
USB_S = STOPPER + SLOT_W / 2

# 背中のボス（腕のパッドを受ける。ナットを横から差す厚みが要る）
# 下端は殻の底と揃える。途中で止めると、その下面が印刷で宙に浮く（実測 640mm2 の
# 要サポート面だった）。底まで伸ばすと造形板に着くので消える。ついでに背板が硬くなる。
BOSS_T     = 0.0100   # 10.0mm
BOSS_Y     = 0.0640   # 64.0mm
BOSS_Z_TOP = 0.0180   # +18.0mm 上端（下端は Z_BOT）

TETHER_R = 0.0020   #  4.0mm 落下保険の紐穴（ボスを長辺方向に貫く）
BEVEL    = 0.0008   #  0.8mm 外周の面取り

# =========================================================================
# クランプ（K 座標）
# =========================================================================
# 肉厚 9mm。天井を 45° の切妻に落とすと頂点が半径 1.414×14.3 = 20.2mm まで上がるので、
# 4.5mm では肉を突き抜けてリングが分断される（実測: 殻が 3 つに割れた）。
# 角のジョイントは構造材でもあるので、厚くする方が都合がよい。
RING_WALL = 0.0090                  #  9.0mm リングの肉厚
RING_R    = BORE_R + RING_WALL      # 23.3mm 外半径
RING_W    = 0.0260                  # 26.0mm 幅（パイプ軸方向）

# 半割りの合わせ面は突き当てない。突き当たると先に面が当たってパイプを掴めない。
SPLIT_GAP = 0.0015                  #  1.5mm 両半分の隙間（片側 0.75mm）

EAR_T  = 0.0080   #  8.0mm 耳の厚み（片側。ボルトの積み上げは 8+1.5+8）
# 耳の内端。ボアぴったり（14.3mm）にすると耳の面がボアの円筒に接する。接する合わせは
# EXACT でも薄片が出るので、0.8mm 外へ逃がす。逃がした分はリングの肉が埋める。
EAR_Y0 = BORE_R + 0.0008
EAR_Y1 = 0.0360   # 36.0mm 耳の外端
BOLT_Y = 0.0280   # 28.0mm ボルト軸（リング外 23.3mm の外、耳の端まで 5.8mm）

ARM_H = 0.0180   # 18.0mm 腕の高さ（Ky）
ARM_W = 0.0260   # 26.0mm 腕の幅（Kz。リングと同じ）

PAD_BOLT_Y = 0.0220   # 22.0mm パッドのボルト間隔の半分（今は使わない）

# M4
BOLT_R = 0.0022   # 4.4mm 通し穴
NUT_AF = 0.0072   # 7.2mm ナットの二面幅（軽い圧入）
NUT_T  = 0.0034   # 3.4mm ナットの厚み
CB_R   = 0.0038   # 7.6mm 頭の座ぐり
CB_D   = 0.0030   # 3.0mm 座ぐりの深さ

# =========================================================================
# 角のジョイントを兼ねる本体（既存の継手と置き換える）
# =========================================================================
# 縦の柱とレールの軸は、どちらも x = CORNER_X の平面に乗っている。そこで割ると
# 2 本ぶんのボアが同じ向きへ開くので、押さえは L 字の 1 個で足りる（部品が減る）。
# 印刷も、その分割面を造形板へ伏せれば両方のボアが「上を向いた樋」になるので、
# 支持材が 1 か所も要らない。
CORNER_X    = 0.4800    # 分割面（2 本の軸が乗る平面）
CORNER_Y    = -0.9550   # 柱の軸
RAIL_Z      = 0.9666    # レール B の軸の高さ
# レールを掴む位置。パイプの端は y=-925mm なので、幅 55mm のクリップが端からはみ出さない
# よう中心を -895mm に置く（端から 2.5mm 内側で始まり、-867.5mm まで掴む）
RAIL_RING_Y = -0.8950
POST_RING_Z = 0.9336    # 柱を掴む位置（レールの 33mm 下）

WEB_Y0, WEB_Y1 = -0.9600, -0.8850   # 2 つのクリップをつなぐ角の肉（背骨）
WEB_Z0, WEB_Z1 = 0.9100, 0.9620

# --- パイプを丸ごと囲む閉じたリング（ねじ無し・差し込みで組む） ---
# 口を開けないので撓ませる必要が無く、肉を厚く取れる。2 本のリングが直交しているので、
# 差し込んでしまえば回転も滑りも形で止まる（ねじが要らないのはこのため）。
CLIP_BORE_R  = 0.01420   # 28.4mm 内径（実測 28.0 に対し片側 0.2mm。滑って入る寸法）
# 掴む長さを 24 → 55mm へ。長いほど傾きに強い（軸受けの長さがそのまま効く）。
# ただし嵌める力は幅に比例するので、腕の肉厚を 2.5 → 2.0mm へ落として相殺する
# （力は厚みの 3 乗。2.29 倍 × 0.51 倍 = 1.17 倍で済む）。歪みも 0.86 → 0.69% へ下がる。
CLIP_WALL    = 0.0070    #  7.0mm リングの肉厚（外径 42.4mm）
CLIP_W       = 0.0550    # 55.0mm 幅（パイプ軸方向）
# 天井の切妻。頂点は半径 1.414×14.2 = 20.1mm なので、外半径 21.2mm の内側に収まる。
# 向きは「印刷したときの真上」＝ポケットを立てた向き（Mz）を各軸へ射影した方向。
# これでボアの中に支持材が入らない（深い筒の中の支持材は取れない）

# 腕は細い棒ではなく厚い板にする。断面 2 次モーメントが幅に比例・厚みの 3 乗に効くので、
# 26×16 → 55×22 で曲げ剛性が 8.9 倍になる。見た目は太いが、そこはこだわらない方針。
ARM_W = 0.0550   # 55.0mm 腕の断面（幅。クリップと揃える）
ARM_H = 0.0220   # 22.0mm 腕の断面（厚み）

# ポケットと本体の合わせ（ねじ無し。舌と穴で位置を決め、面で接着する）
PAD_T   = 0.0120   # 12.0mm パッドの厚み（穴 5.5mm を掘っても 6.5mm 残る）
PAD_Y   = 0.0600   # 60.0mm 合わせ面
PAD_Z   = 0.0340   # 34.0mm
KEY_Y   = 0.0400   # 40.0mm 舌の寸法
KEY_Z   = 0.0140   # 14.0mm
KEY_D   = 0.0055   #  5.5mm 舌の出（＝穴の深さ）
KEY_CLR = 0.00025  # 0.25mm 片側の隙間（接着剤が回る）

