# Pixel 7a 壁掛けマウント 横 45° 振り — 寸法・定数（単位: m）
# 正面版 models/pixel7a-wallmount との違いは YAW_DEG と、それに伴う背板・ガセットだけ。
import math

# --- Pixel 7a 実寸（Google 公式スペック） ---
PHONE_L    = 0.1520   # 152.0mm 長辺（横向きに入れるので X 方向）
PHONE_W    = 0.0729   # 72.9mm 短辺（スロットを上る方向）
PHONE_T    = 0.0090   # 9.0mm 厚み（カメラバー部を除く）
PHONE_BUMP = 0.0011   # カメラバーの出っ張り 1.1mm（窓から外へ出す）

# --- クリアランス（片側）— 据置版で実機が入った値をそのまま使う ---
CLR_L = 0.0007   # 長辺方向 0.7mm
CLR_W = 0.0007   # 短辺方向 0.7mm
CLR_T = 0.0008   # 厚み方向 0.8mm

# --- スロット内寸 ---
SLOT_L = PHONE_L + 2 * CLR_L   # 153.4mm 長辺方向（X）
SLOT_W = PHONE_W + 2 * CLR_W   #  74.3mm 短辺方向（s）
SLOT_T = PHONE_T + CLR_T       #   9.8mm 厚み方向（h）

# --- 肉厚 ---
FRONT_SKIN = 0.0025   # 2.5mm 外皮。スマホ背面を下から受ける面で、カメラ窓が開く
BACK_PLATE = 0.0030   # 3.0mm 裏板。スマホ画面側で上を向く
SIDE_WALL  = 0.0035   # 3.5mm 側壁（左右のガセットを兼ねる）
PLATE_T    = 0.0055   # 5.5mm 壁に留める背板（皿座繰り 2.4mm を彫っても 3.1mm 残る）
GUSSET_W   = 0.0060   # 6.0mm 中央のガセット（背板とスロット部を繋ぐ）
STOPPER    = 0.0035   # 3.5mm スロット下端の受け（スマホはここで止まる）

SHELL_TOTAL = FRONT_SKIN + SLOT_T + BACK_PLATE   # 15.3mm スロット部の総厚

# --- 姿勢 ---
# スマホ面を水平から TILT_DEG 倒す。背面の法線＝カメラの視線は (90 - TILT) 度だけ下を向く。
TILT_DEG      = 50.0
CAM_DEPRESSION = 90.0 - TILT_DEG   # 40.0° カメラの俯角

SLOPE_LEN  = STOPPER + SLOT_W + 0.0008   # 78.6mm スロット部の長さ
SLOT_ENTRY = 0.0600   # 差し込み口を抜くためのカッター延長

# --- 横振り（垂直軸まわりの回転） ---
# スロット部だけを Z 軸で回す。壁（y=0）と背板の向きは正面版のまま。
# 正なら壁を背にして見て左へ、負なら右へカメラが振れる。
YAW_DEG = 45.0

# --- 外形 ---
MOUNT_W = SLOT_L + 2 * SIDE_WALL   # 160.4mm
PLATE_H = 0.0850                   # 85.0mm 壁に接する高さ

# --- 背板とガセット（横振りで生じる背板とスロット部の隙間を渡す） ---
PLATE_MARGIN = 0.0060   # 6.0mm 背板をスロット部の投影より外へ広げる量
GUSSET_T     = 0.0040   # 4.0mm ガセット 1 枚の厚み
GUSSET_N     = 7        # 背板の幅に等間隔で立てる枚数
GUSSET_MIN   = 0.0080   # 8.0mm これより短くなるガセットは作らない
GUSSET_BITE  = 0.0006   # 0.6mm 背板とスロット部へ食い込ませる量（重なりで一体化させる）
BAND_H       = 0.0240   # 24.0mm ガセットは上下の帯だけにする（箱の中なので見えない）

# --- 外装（左右・底・上を張って箱にする） ---
COVER_T    = 0.0020   # 2.0mm 外装の板厚（背板を厚くしたぶんここで戻す）
GRIP_DEPTH = 0.0600   # 60.0mm 指がかりを背板側まで貫く深さ。外装で塞がないため

# --- ねじ止め ---
# 45° 振りは重心が壁から 71mm 離れ、貼付面の上端に 389gf の引き剥がしがかかる。
# 両面テープでは経時のクリープが怖いので M4 の皿ねじで留める。貼付面は平らなまま
# 残してあるので、テープ併用もできる。
SCREW_D     = 0.0045   # 4.5mm 通し穴（M4 のバカ穴）
SCREW_HEAD  = 0.0090   # 9.0mm 皿座繰りの上口径
SCREW_SINK  = 0.0024   # 2.4mm 座繰りの深さ
SCREW_INSET = 0.0150   # 15.0mm 背板の上下端から穴の中心までの距離

# --- カメラ窓（外皮を貫通。カメラバーはここから外へ出る） ---
CAM_EDGE_RIM = 0.0040   # 4.0mm スマホ上端側に残す外皮リム
CAM_WIN_L    = 0.0340   # 34.0mm 窓の長さ（端末上端から 4〜38mm を覆う）
WIN_S_MIN    = 0.0030
WIN_S_MAX    = SLOPE_LEN + 0.0040   # 差し込み口まで抜く（窓の上に橋を架けない）
WIN_S_LEN    = WIN_S_MAX - WIN_S_MIN
WIN_S_CENTER = (WIN_S_MIN + WIN_S_MAX) / 2

# --- 差し込み口のテーパー（外皮側だけ広げて導入する） ---
TAPER_S0  = 0.0665
TAPER_LEN = 0.0140
TAPER_D   = 0.0012   # 入口で 1.2mm 逃がす（外皮は 1.3mm 残る）
TAPER_CUT = 0.0040   # カッターの厚み。テーパー面からスロット側へこれだけ抜く。
                     # 薄いと外皮の内面側だけ削れて外面が膜として残り、隙間ができる

# --- 指がかり（スマホの上端を表裏から摘まむ切り欠き） ---
GRIP_W  = 0.0460   # 46.0mm 幅（中央）
GRIP_S0 = 0.0635   # ここから上端まで外皮と裏板を落とす

# --- USB-C / スピーカーの逃げ（スマホ下端側の側壁を切り欠く） ---
USB_W = 0.0200   # 20.0mm 切り欠きの長さ（s 方向）
USB_T = 0.0170   # 17.0mm 厚み方向。側壁を貫いてケーブルを自由に通す
USB_INTO = 0.0015  # 1.5mm スロット側へ食い込ませる量。0.5mm だと切り口が
                   # ノズル幅ほどの段差になり、印刷で潰れる
USB_S = STOPPER + SLOT_W / 2

# 貼付面（背板の裏）は座繰りを彫らず完全な平面にしてある。
# 彫るとテープの厚みばらつきで周囲の平面が先に壁へ当たり、かえって密着が落ちる。
