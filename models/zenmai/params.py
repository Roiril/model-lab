# ゼンマイ（平面渦巻きトーションばね）回転機構 — 寸法・定数（単位: m）
#
# 構造（平面・z上向きに押し出し）:
#   中心アーバー（巻き軸） — 渦巻きばね — 外周バレル（固定リング）
#   3者がばね1本でのみ繋がる一体物。バレルを持って軸をひねるとばねが
#   巻かれてトルクを蓄え、離すと逆回転して戻る。
# サポート不要・立ててプリント可（平面形状の押し出しのため）。

import math  # noqa: F401

# --- ばね本体（渦巻き）---
SPRING_T = 0.0014   # 1.4mm ばね肉厚（FDM最小肉厚以上。薄いほど巻けるが弱い）
HEIGHT   = 0.006    # 6mm 押し出し高さ（トルクに効く。高いほど強い）
TURNS    = 3.5      # 渦巻きの巻き数

# --- 半径方向レイアウト ---
HUB_CL_R   = 0.004   # 4mm  ばね内端の中心線半径（アーバー接続）
RING_CL_R  = 0.022   # 22mm ばね外端の中心線半径（バレル接続）
# 隣接ターン間ピッチ = (RING_CL_R - HUB_CL_R) / TURNS ≈ 5.1mm
# 壁間ギャップ ≈ ピッチ - SPRING_T ≈ 3.7mm（巻き込みの余裕）

# --- 中心アーバー（巻き軸）---
HUB_R = HUB_CL_R + SPRING_T / 2 + 0.0008  # ばね内端を包む半径 ≈ 5.5mm
KEY_SIZE = 0.0035   # 3.5mm 角の巻きキー穴（角棒を挿して巻く／出力を取る）

# --- 外周バレル（固定リング）---
RING_IR = RING_CL_R - SPRING_T / 2 - 0.0008  # ばね外端を包む内半径 ≈ 20.5mm
RING_WALL = 0.004   # 4mm リング肉厚（しっかりアンカー）
RING_OR = RING_CL_R + SPRING_T / 2 + RING_WALL  # 外半径 ≈ 26.7mm

# --- バレル固定用の取り付け穴（2か所）---
MOUNT_HOLE_R = 0.0016   # 1.6mm 半径（M3 ゆるめ）
MOUNT_HOLE_PCD = RING_CL_R + SPRING_T / 2 + RING_WALL / 2  # 穴の配置半径

# --- メッシュ解像度 ---
SPIRAL_SEGS = 240   # 渦巻き中心線の分割数
